// Exhaustive AST census. This is a migration-obligation report, NOT verification.
import {readFile,readdir,writeFile} from "node:fs/promises";
import {parse} from "../../web/mathscript/parser.mjs";
import {fileURLToPath} from "node:url";
import {execFileSync} from "node:child_process";
const proofRoot=new URL("../../web/proofs/",import.meta.url);
const obligations={
  identity_elimination:["path_induction","based_induction","transport","apd","trans","sym","cong"],
  univalence:["ua","Univalence","UnivalenceBeta","UnivalenceEta","idtoequiv"],
  function_extensionality:["FunExt"],
  truncation:["Truncate","TruncateIntro","TruncateElim","TruncateProp"],
  choice:["Choice"], excluded_middle:["LEM"],
  suspension:["Suspension","north","south","merid","suspension_induction","suspension_recursion"],
  universe_polymorphism:["Universe"], w_type:["W","sup","w_induction"],
};
function scan(node,kinds,names) {
  if(!node||typeof node!=="object") return;
  if(node.kind) kinds[node.kind]=(kinds[node.kind]??0)+1;
  if(node.kind==="name") names.add(node.name);
  for(const [key,value] of Object.entries(node)) {
    if(["valueParameters","params"].includes(key)&&node.value) continue; // parser keeps source metadata twice
    if(Array.isArray(value)) value.forEach(x=>scan(x,kinds,names));
    else if(typeof value==="object") scan(value,kinds,names);
  }
}
export async function inventory() {
  const modules=[], files=(await readdir(proofRoot)).sort();
  const constructions=files.filter(n=>n.endsWith(".construction.proof"));
  for(const file of files.filter(n=>n.endsWith(".proof")&&!n.endsWith(".construction.proof"))) {
    const ast=parse(await readFile(new URL(file,proofRoot),"utf8")), kinds={}, names=new Set();
    scan(ast,kinds,names);
    modules.push({module:file.slice(0,-6),imports:ast.imports,declarations:ast.declarations.map(d=>({name:d.name.text,kind:d.kind,status:"not-translated"})),
      syntax:kinds, directObligations:Object.fromEntries(Object.entries(obligations).map(([key,words])=>[key,words.filter(w=>names.has(w))]).filter(([,words])=>words.length))});
  }
  const byName=new Map(modules.map(m=>[m.module,m]));
  for(const m of modules) {
    const visited=new Set(), transitive=new Set();
    const visit=n=>{if(visited.has(n))return;visited.add(n);if(n==="prelude"){transitive.add("kernel_prelude_exports");return;}const dep=byName.get(n);if(!dep)throw Error(`Missing source import ${n}`);
      Object.keys(dep.directObligations).forEach(x=>transitive.add(x));dep.imports.forEach(visit);};
    visit(m.module);m.transitiveObligations=[...transitive].sort();
  }
  const sourceRevision=execFileSync("git",["log","-1","--format=%H","--","web/proofs"],{cwd:fileURLToPath(new URL("../../",import.meta.url)),encoding:"utf8"}).trim();
  return {meaning:"AST inventory only; statuses are not claims of kernel verification",sourceRevision,sourceModules:modules.length,legacyConstructionArtifacts:constructions,
    declarations:modules.reduce((n,m)=>n+m.declarations.length,0),translated:0,modules};
}
if(process.argv[1]===fileURLToPath(import.meta.url)) {
  const result=await inventory(), json=new URL("../../docs/cubical/migration-inventory.json",import.meta.url);
  await writeFile(json,JSON.stringify(result,null,2)+"\n");
  const rows=result.modules.map(m=>`| ${m.module} | ${m.declarations.length} | ${m.transitiveObligations.join(", ")||"structural/type-former translation"} |`);
  await writeFile(new URL("../../docs/cubical/migration-inventory.md",import.meta.url),
    `# Whole-library cubical migration inventory\n\nGenerated by \`node experiments/cubical/inventory.mjs\`.\n\n${result.sourceModules} source modules; ${result.declarations} declarations; **0 declarations certified translated by this inventory**. This AST scan records direct and transitive syntactic obligations. It is not an axiom dependency audit: references can be shadowed, derived declarations can hide dependencies, and the source compiler supplies foundational builtins. The JSON contains every declaration, including paused analysis.\n\n| Module | Declarations | Obligations including imports |\n|---|---:|---|\n${rows.join("\n")}\n`);
  console.log(`${result.sourceModules} modules, ${result.declarations} declarations inventoried; no translation inferred from parsing.`);
}
